import board
import busio
import adafruit_ads1x15.ads1115 as ADS
from adafruit_ads1x15.analog_in import AnalogIn
import smbus2
import time

# ─── ADS1115 ───────────────────────────────────────
i2c = busio.I2C(board.SCL, board.SDA)
ads = ADS.ADS1115(i2c)
ph_channel  = AnalogIn(ads, 3)
tds_channel = AnalogIn(ads, 1)

def read_ph(voltage):
    # Calibration: pH7 = 2.5V, slope ~0.18V/pH unit
    ph = 7 + ((2.5 - voltage) / 0.18)
    return round(ph, 2)

def read_ec(voltage):
    # Raw EC estimate from TDS sensor voltage
    tds_ppm = (voltage / 2.3) * 1000
    ec = tds_ppm * 2 / 1000  # EC in mS/cm
    return round(ec, 2), round(tds_ppm, 1)

# ─── OLED (SH1106) ─────────────────────────────────
bus = smbus2.SMBus(1)
OLED_ADDR = 0x3C

def oled_cmd(c):
    bus.write_byte_data(OLED_ADDR, 0x00, c)

def oled_init():
    for c in [0xAE,0xD5,0x80,0xA8,0x3F,0xD3,0x00,0x40,
              0xAD,0x8B,0xA1,0xC8,0xDA,0x12,0x81,0xFF,
              0xD9,0x1F,0xDB,0x40,0xA4,0xA6,0xAF]:
        oled_cmd(c)

def oled_clear():
    for page in range(8):
        oled_cmd(0xB0 + page)
        oled_cmd(0x02)
        oled_cmd(0x10)
        for _ in range(128):
            bus.write_byte_data(OLED_ADDR, 0x40, 0x00)

