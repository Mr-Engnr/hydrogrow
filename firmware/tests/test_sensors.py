def oled_write(page, text):
    oled_cmd(0xB0 + page)
    oled_cmd(0x02)
    oled_cmd(0x10)
    for ch in text.upper():
        for byte in FONT.get(ch, [0x00]*5):
            bus.write_byte_data(OLED_ADDR, 0x40, byte)
        bus.write_byte_data(OLED_ADDR, 0x40, 0x00)

# ─── MAIN LOOP ─────────────────────────────────────
print("Initializing OLED...")
oled_init()
oled_clear()
oled_write(0, "HYDROGROW")
oled_write(2, "STARTING...")
time.sleep(1)

print("Starting sensor reads. Ctrl+C to stop.\n")

try:
    while True:
        ph_v  = ph_channel.voltage
        tds_v = tds_channel.voltage

        ph_val       = read_ph(ph_v)
        ec_val, tds  = read_ec(tds_v)

        print(f"pH:  {ph_val}  (raw {ph_v:.3f}V)")
        print(f"EC:  {ec_val} mS/cm  TDS: {tds} ppm  (raw {tds_v:.3f}V)")
        print("─" * 40)

        # Update OLED
        oled_clear()
        oled_write(0, "HYDROGROW")
        oled_write(2, f"PH {ph_val}")
        oled_write(4, f"EC {ec_val}")

        time.sleep(2)

except KeyboardInterrupt:
    oled_clear()
    oled_write(0, "STOPPED")
    print("\nStopped.")
